"""Generates js/foods.js from tools/foodref/foodref.json. Run from src/: python3 tools/gen_foods.py"""
import json, re, pathlib
d = json.load(open('tools/foodref/foodref.json'))
OIL = re.compile(r'炒|炸|唐揚|天婦羅|甜不辣|薯條|油條|煎餃|鍋貼|洋芋片|鹽酥|荷包蛋（加油|油豆腐|豆皮|蔥油餅|餡餅|水煎包|韭菜盒子|蚵仔煎|棺材板|可樂餅|春捲|大阪燒|金平|涼拌|玉子燒|麻婆|糖醋|燴|咖哩|丼料|漢堡排|燉肉|泡麵')
ALIAS = {'白飯': ['米飯', '蓬萊米飯', '白米飯'], '糙米飯': ['五穀飯'], '茶葉蛋': [], '可樂': ['可口可樂'],
         '油麵／拉麵（煮）': ['油麵', '拉麵麵條', '陽春麵麵條'], '烏龍麵（煮）': ['烏龍麵'], '冬粉（煮）': ['冬粉'],
         '高麗菜（炒）': ['炒高麗菜', '清炒高麗菜'], '水煮蛋': ['白煮蛋'], '薯條': ['炸薯條']}
rows = []
for x in d:
    n = x['n']
    # TFND prepared dishes (R/Q codes) and JP prepared dishes (18xxx) are as-served: oil already in the measured value
    ready = (x['s'] == 'TW' and x['code'][0] in 'RQ') or (x['s'] == 'JP' and x['code'].startswith('18')) or bool(OIL.search(n))
    if n in ('荷包蛋（不加油）', '煎蛋（不加油）', '豆腐皮', '蘿蔔糕（未煎）'): ready = False
    if n in ('豆漿（含糖）', '米漿', '鹹豆漿（含油條）'): ready = True
    src = 'TFND' if x['s'] == 'TW' else 'MEXT'
    srcName = (f"衛福部食品營養成分資料庫 {x['code']}" if x['s'] == 'TW' else f"日本食品標準成分表（八訂）{x['code']}")
    rows.append(dict(id=x['id'], key=n, aliases=ALIAS.get(n, []), p=x['p'], c=x['c'], f=x['f'], oilIncluded=ready, src=src, srcName=srcName))
body = ',\n'.join('  ' + json.dumps(r, ensure_ascii=False, separators=(', ', ': ')) for r in rows)
head = pathlib.Path('js/foods.js').read_text().split('const FOOD_TABLE')[0]
head = head.replace(" * Values are per 100 g of the edible part AS SERVED, before any added cooking oil\n * (the app adds oil from the cooking method; see COOK_METHODS in app.js).",
 " * Values are per 100 g of the edible part AS SERVED.\n *  - oilIncluded: true  → the measured dish already contains its cooking/frying oil\n *    (炒, 炸, prepared dishes); the app adds nothing.\n *  - oilIncluded: false → plain cooked form; the app adds oil from the cooking method.\n * Generated by tools/gen_foods.py from TFND (衛福部) and MEXT 八訂 data — do not hand-edit values.")
head = head.replace(" *  - Only cooked / ready-to-eat forms (rice, boiled egg, blanched vegetables…).\n", " *  - Only cooked / ready-to-eat forms, never raw ingredients.\n")
pathlib.Path('js/foods.js').write_text(head + 'const FOOD_TABLE = [\n' + body + '\n];\n')
print(len(rows), sum(r['oilIncluded'] for r in rows))
